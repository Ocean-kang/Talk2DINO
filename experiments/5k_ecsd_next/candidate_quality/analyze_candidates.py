#!/usr/bin/env python3
"""Candidate-pool and selected-caption quality diagnostics for legacy ECSD."""
import argparse
import csv
import importlib.util
import json
import sys
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
NEXT_ROOT = HERE.parent
REPO_ROOT = NEXT_ROOT.parents[1]
sys.path.insert(0, str(NEXT_ROOT))

from candidate_quality.semantic_role_classifier import (
    classify_semantic_roles, content_tokens, normalize_text, quality_flags,
)

def load_legacy_core():
    path = REPO_ROOT / "experiments" / "5k_ecsd" / "ecsd_core.py"
    if not path.is_file():
        raise FileNotFoundError("Expected existing ECSD core at {}".format(path))
    spec = importlib.util.spec_from_file_location("ecsd_legacy_core", str(path))
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module

def load_rows(path):
    rows = json.loads(Path(path).read_text(encoding="utf-8"))
    if not isinstance(rows, list):
        raise ValueError("Caption JSON must be a list.")
    ids = [int(x["image_id"]) for x in rows]
    if len(ids) != len(set(ids)):
        raise ValueError("Duplicate image_id in caption JSON.")
    for row in rows:
        raw = row.get("raw_captions")
        if not isinstance(raw, list) or len(raw) != 5:
            raise ValueError("image_id={} must have five raw captions.".format(row["image_id"]))
    return rows

def load_selected(path, field):
    rows = load_rows(path)
    result = {}
    for row in rows:
        captions = row.get(field)
        if not isinstance(captions, list) or len(captions) != 5:
            raise ValueError("image_id={} missing five captions in field {}.".format(row["image_id"], field))
        result[int(row["image_id"])] = captions
    return result

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", default="data/coco2014_subset_50k/5k_rich_diversity.json")
    parser.add_argument("--selected-json", required=True,
                        help="Legacy ECSD JSON generated by experiments/5k_ecsd/generate_ecsd.py")
    parser.add_argument("--selected-field", default="ecsd_captions")
    parser.add_argument("--output-dir", default="outputs/5k_ecsd_next/candidate_quality")
    parser.add_argument("--expected-images", type=int, default=5000)
    args = parser.parse_args()

    rows = load_rows(args.input)
    if args.expected_images and len(rows) != args.expected_images:
        raise ValueError("Expected {} images, found {}.".format(args.expected_images, len(rows)))
    selected = load_selected(args.selected_json, args.selected_field)
    selected_source_rows = load_rows(args.selected_json)
    selected_source_map = {int(x["image_id"]): x["raw_captions"] for x in selected_source_rows}
    source_map = {int(x["image_id"]): x["raw_captions"] for x in rows}
    if set(selected) != set(source_map):
        raise ValueError("Selected-caption image IDs do not match source IDs.")
    if selected_source_map != source_map:
        raise ValueError("Selected JSON Raw Captions differ from the source file; do not mix caption versions.")

    legacy = load_legacy_core()
    per_image = []
    pool_summary = Counter()
    selected_summary = Counter()
    pool_type = Counter()
    selected_type = Counter()
    pool_category = Counter()
    selected_category = Counter()
    raw_category = Counter()
    pool_invalid = pool_duplicate = pool_unsupported = 0
    selected_invalid = selected_duplicate = selected_unsupported = 0
    pool_content_n, pool_sentence_n = [], []
    selected_content_n, selected_sentence_n = [], []
    per_candidate_rows = []

    for row in rows:
        image_id = int(row["image_id"])
        raw = row["raw_captions"]
        source_facts = set().union(*(content_tokens(x) for x in raw))
        for raw_caption in raw:
            raw_category.update(classify_semantic_roles(raw_caption)["categories"])
        candidates = legacy.build_candidates(raw)
        chosen = selected[image_id]
        chosen_counts = Counter(normalize_text(x) for x in chosen)
        candidate_by_text = {}
        seen_pool = set()

        for item in candidates:
            candidate_by_text.setdefault(normalize_text(item["text"]), item)
            text = item["text"]
            facts = set(item.get("facts") or content_tokens(text))
            flags = quality_flags(text, item.get("candidate_type", "candidate"))
            key = normalize_text(text)
            duplicate = bool(key and key in seen_pool)
            if key:
                seen_pool.add(key)
            pool_invalid += bool(flags)
            pool_duplicate += duplicate
            pool_unsupported += bool(facts - source_facts)
            pool_type[item.get("candidate_type", "unknown")] += 1
            pool_category.update(classify_semantic_roles(text)["categories"])
            pool_content_n.append(len(facts))
            pool_sentence_n.append(len(text.split()))
            per_candidate_rows.append({
                "image_id": image_id,
                "candidate_id": item.get("candidate_id", ""),
                "candidate_type": item.get("candidate_type", ""),
                "text": text,
                "content_token_count": len(facts),
                "sentence_token_count": len(text.split()),
                "invalid_flags": "|".join(flags),
                "unsupported_tokens": "|".join(sorted(facts - source_facts)),
                "categories": "|".join(classify_semantic_roles(text)["categories"]),
                "selection_frequency": chosen_counts.get(key, 0),
                "is_selected": chosen_counts.get(key, 0) > 0,
                "source_caption_ids": json.dumps(item.get("source_caption_ids", [])),
                "source_spans": json.dumps(item.get("source_spans", []), ensure_ascii=False),
            })

        selected_seen = set()
        chosen_items = []
        for idx, text in enumerate(chosen):
            matched = candidate_by_text.get(normalize_text(text))
            ctype = matched.get("candidate_type", "unmatched") if matched else "unmatched"
            facts = set(matched.get("facts", [])) if matched else content_tokens(text)
            flags = quality_flags(text, ctype)
            key = normalize_text(text)
            duplicate = bool(key and key in selected_seen)
            if key:
                selected_seen.add(key)
            selected_invalid += bool(flags)
            selected_duplicate += duplicate
            selected_unsupported += bool(facts - source_facts)
            selected_type[ctype] += 1
            selected_category.update(classify_semantic_roles(text)["categories"])
            selected_content_n.append(len(facts))
            selected_sentence_n.append(len(text.split()))
            chosen_items.append(text)

        raw_categories = set()
        selected_categories = set()
        pool_categories = set()
        for candidate in candidates:
            pool_categories.update(
                x for x in classify_semantic_roles(candidate["text"])["categories"] if x != "Unknown"
            )
        for text in raw:
            raw_categories.update(x for x in classify_semantic_roles(text)["categories"] if x != "Unknown")
        for text in chosen:
            selected_categories.update(x for x in classify_semantic_roles(text)["categories"] if x != "Unknown")
        per_image.append({
            "image_id": image_id,
            "candidate_count": len(candidates),
            "selected_caption_count": len(chosen),
            "raw_category_count": len(raw_categories),
            "candidate_pool_category_count": len(pool_categories),
            "candidate_pool_category_coverage_ratio": len(pool_categories) / 5.0,
            "selected_category_count": len(selected_categories),
            "selected_categories": "|".join(sorted(selected_categories)),
            "selected_category_coverage_ratio": len(selected_categories) / 5.0,
        })

    n_pool = len(per_candidate_rows)
    n_selected = len(rows) * 5
    def make_summary(n, types, cats, invalid, duplicate, unsupported, content, sentence):
        return {
            "count": n,
            "candidate_type_counts": dict(types),
            "category_counts": dict(cats),
            "invalid_count": int(invalid),
            "invalid_ratio": invalid / n if n else 0.0,
            "duplicate_count": int(duplicate),
            "duplicate_ratio": duplicate / n if n else 0.0,
            "unsupported_content_count": int(unsupported),
            "unsupported_content_ratio": unsupported / n if n else 0.0,
            "mean_content_token_count": sum(content) / len(content) if content else 0.0,
            "mean_sentence_token_count": sum(sentence) / len(sentence) if sentence else 0.0,
        }
    summary = {
        "status": "ok",
        "num_images": len(rows),
        "selected_field": args.selected_field,
        "candidate_pool": make_summary(
            n_pool, pool_type, pool_category, pool_invalid, pool_duplicate,
            pool_unsupported, pool_content_n, pool_sentence_n),
        "selected_five_per_image": make_summary(
            n_selected, selected_type, selected_category, selected_invalid,
            selected_duplicate, selected_unsupported, selected_content_n, selected_sentence_n),
        "raw_caption_category_counts": dict(raw_category),
        "interpretation_warning": (
            "Invalidity and unsupported-content are lexical heuristics, not human-verified correctness. "
            "Category labels are rule matches, not semantic ground truth."
        ),
    }

    out = Path(args.output_dir)
    out.mkdir(parents=True, exist_ok=True)
    (out / "summary.json").write_text(json.dumps(summary, indent=2), encoding="utf-8")
    with (out / "summary.csv").open("w", newline="", encoding="utf-8-sig") as f:
        fields = ["scope", "count", "invalid_ratio", "duplicate_ratio",
                  "unsupported_content_ratio", "mean_content_token_count",
                  "mean_sentence_token_count", "candidate_type_counts", "category_counts", "raw_category_counts"]
        writer = csv.DictWriter(f, fieldnames=fields)
        writer.writeheader()
        for scope in ("candidate_pool", "selected_five_per_image"):
            item = summary[scope]
            writer.writerow({
                "scope": scope, "count": item["count"],
                "invalid_ratio": item["invalid_ratio"],
                "duplicate_ratio": item["duplicate_ratio"],
                "unsupported_content_ratio": item["unsupported_content_ratio"],
                "mean_content_token_count": item["mean_content_token_count"],
                "mean_sentence_token_count": item["mean_sentence_token_count"],
                "candidate_type_counts": json.dumps(item["candidate_type_counts"]),
                "category_counts": json.dumps(item["category_counts"]),
                "raw_category_counts": json.dumps(summary["raw_caption_category_counts"]),
            })
    with (out / "per_image_category_coverage.csv").open("w", newline="", encoding="utf-8-sig") as f:
        writer = csv.DictWriter(f, fieldnames=list(per_image[0].keys()))
        writer.writeheader()
        writer.writerows(per_image)
    with (out / "per_candidate.csv").open("w", newline="", encoding="utf-8-sig") as f:
        writer = csv.DictWriter(f, fieldnames=list(per_candidate_rows[0].keys()))
        writer.writeheader()
        writer.writerows(per_candidate_rows)
    print("[DONE] Candidate quality report:", out / "summary.json")

if __name__ == "__main__":
    main()
